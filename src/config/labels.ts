export const label = (key: string) => labels[key] || '补充信息';
export function display(value: unknown): string {
  if (value === null || value === undefined || value === '') return '—';
  if (typeof value === 'boolean') return value ? '是' : '否';
  if (Array.isArray(value)) return value.length ? value.map(display).join('、') : '—';
  if (typeof value === 'object')
    return Object.entries(value)
      .map(([k, v]) => `${label(k)}：${display(v)}`)
      .join('；');
  const s = String(value);
  if (values[s]) return values[s];
  if (/^\d{4}-\d\d-\d\dT/.test(s)) return new Date(s).toLocaleString('zh-CN', { hour12: false });
  return s;
}
